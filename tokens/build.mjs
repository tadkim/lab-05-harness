// figma-variables.json → tokens.css
// Usage: node tokens/build.mjs
//
// - Variable name `a/b/c` becomes `--a-b-c` (matches the WEB code syntax set in Figma).
// - Aliases stay aliases: `var(--target)`.
// - First mode of each collection is the :root default. Other modes become overrides:
//     typography `en`      → :lang(en)
//     editorial  `desktop` → @media (min-width: DESKTOP_MIN)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(here, 'figma-variables.json'), 'utf8'));

// Figma has no breakpoint variable; the reference frames are 360 (mobile) and 1440 (desktop).
const DESKTOP_MIN = '1024px';
const MODE_SELECTORS = {
  'DS-local/typography': { en: ':root:lang(en), [lang="en"]' },
  'DS-local/editorial': { desktop: `@media (min-width: ${DESKTOP_MIN})` },
};
const FONT_FALLBACK = '-apple-system, BlinkMacSystemFont, "Apple SD Gothic Neo", "Noto Sans KR", sans-serif';
const WEIGHTS = { Regular: 400, Medium: 500, Semibold: 600, Bold: 700 };

const cssName = (name) => '--' + name.replace(/[\/\s]+/g, '-');
const known = new Set(src.collections.flatMap((c) => c.v.map(([n]) => n)));

function cssValue(name, type, raw) {
  if (typeof raw === 'string' && raw.startsWith('@')) {
    const target = raw.slice(1);
    if (!known.has(target)) throw new Error(`${name}: alias target not found: ${target}`);
    return `var(${cssName(target)})`;
  }
  if (type === 'C') return raw.toLowerCase();
  if (type === 'F') return raw === 0 ? '0' : `${raw}px`;
  if (name.includes('weight')) {
    if (!(raw in WEIGHTS)) throw new Error(`${name}: unknown weight ${raw}`);
    return String(WEIGHTS[raw]);
  }
  if (name.includes('font-family')) return `"${raw}", ${FONT_FALLBACK}`;
  return JSON.stringify(raw);
}

const rootLines = [];
const overrides = [];
const seen = new Set();

for (const col of src.collections) {
  rootLines.push(`\n  /* ${col.c} — ${col.m[0]} */`);
  const perMode = col.m.slice(1).map(() => []);
  for (const [name, type, value] of col.v) {
    const css = cssName(name);
    if (seen.has(css)) throw new Error(`duplicate CSS variable ${css}`);
    seen.add(css);
    const values = Array.isArray(value) ? value : [value];
    const base = cssValue(name, type, values[0]);
    rootLines.push(`  ${css}: ${base};`);
    values.slice(1).forEach((v, i) => {
      const next = cssValue(name, type, v);
      if (next !== base) perMode[i].push(`  ${css}: ${next};`);
    });
  }
  col.m.slice(1).forEach((mode, i) => {
    if (!perMode[i].length) return;
    const sel = MODE_SELECTORS[col.c]?.[mode];
    if (!sel) throw new Error(`no selector configured for ${col.c} mode ${mode}`);
    const body = perMode[i].join('\n');
    overrides.push(
      sel.startsWith('@media')
        ? `\n/* ${col.c} — ${mode} */\n${sel} {\n  :root {\n${body.replace(/^/gm, '  ')}\n  }\n}`
        : `\n/* ${col.c} — ${mode} */\n${sel} {\n${body}\n}`,
    );
  });
}

const out = `/* Generated by tokens/build.mjs from figma-variables.json — do not edit by hand. */
/* Source: ${src.source} (exported ${src.exportedAt}) */

:root {${rootLines.join('\n')}
}
${overrides.join('\n')}
`;

writeFileSync(join(here, 'tokens.css'), out);
console.log(`tokens.css: ${seen.size} variables, ${overrides.length} mode override blocks`);
